r"""Exact perfect-matching blockers and qutrit Tutte-barrier charts.

Let ``J`` be the squarefree monomial ideal generated by the perfect-matching
monomials of ``K_(2m)``.  Its minimal primes are indexed by inclusion-minimal
edge sets meeting every perfect matching.  Equivalently, their complements
are edge-maximal graphs without a perfect matching.

Tutte's theorem gives a compact classification.  Every such complement is

    K_s join (K_(a_1) disjoint-union ... disjoint-union K_(a_(s+2))),

where all ``a_i`` are positive and odd and their sum is ``2m-s``.  This
module enumerates those symmetry types, verifies their blocker property, and
constructs the affine product-vector charts obtained after normalizing one
color coordinate to one.

For qutrits at ``n=8``, two blocker systems are square.  Their exact top Chow
coefficients are 30 and 24.  A positive projective intersection count does
not prove that a solution lies in a chosen affine color chart; boundary
escape remains an open condition.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass
from fractions import Fraction
from itertools import product
from math import factorial
from typing import Mapping, Sequence, TypeAlias

from experiments.krenn_quantum_graph.system import (
    canonical_edges,
    perfect_matchings,
    validate_parameters,
    variable_index,
)
from experiments.krenn_quantum_graph.witness import SparseWitness


Edge: TypeAlias = tuple[int, int]
AffineMonomial: TypeAlias = tuple[int, ...]
AffineTerm: TypeAlias = tuple[AffineMonomial, Fraction]
AffinePolynomial: TypeAlias = tuple[AffineTerm, ...]
ExactScalar: TypeAlias = int | Fraction


class KrennPerfectMatchingBlockerError(ValueError):
    """A blocker type, chart, or exact combinatorial check is malformed."""


def _exact_fraction(value: ExactScalar, label: str) -> Fraction:
    if isinstance(value, bool) or not isinstance(value, (int, Fraction)):
        raise KrennPerfectMatchingBlockerError(
            f"{label} must be an exact integer or rational"
        )
    return Fraction(value)


def _exact_integer(value: int, label: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise KrennPerfectMatchingBlockerError(
            f"{label} must be an exact integer"
        )
    return value


def _canonical_edge(n: int, edge: Sequence[int]) -> Edge:
    if len(edge) != 2:
        raise KrennPerfectMatchingBlockerError(
            "a blocker edge must contain two vertices"
        )
    first, second = (
        _exact_integer(value, "blocker vertex") for value in edge
    )
    if (
        first == second
        or first < 0
        or second < 0
        or first >= n
        or second >= n
    ):
        raise KrennPerfectMatchingBlockerError(
            "a blocker edge needs two distinct elements of range(n)"
        )
    return (first, second) if first < second else (second, first)


def _odd_partitions(
    total: int,
    parts: int,
    maximum: int | None = None,
) -> tuple[tuple[int, ...], ...]:
    if parts == 0:
        return ((),) if total == 0 else ()
    if total < parts or (total - parts) % 2:
        return ()
    upper = total if maximum is None else min(total, maximum)
    result = []
    for first in range(upper, 0, -1):
        if first % 2 == 0:
            continue
        remainder = total - first
        if remainder < parts - 1:
            continue
        for tail in _odd_partitions(remainder, parts - 1, first):
            result.append((first, *tail))
    return tuple(result)


@dataclass(frozen=True)
class PerfectMatchingBlockerType:
    """One ``S_n`` orbit type of a minimal perfect-matching blocker."""

    n: int
    barrier_size: int
    odd_component_sizes: tuple[int, ...]

    def __post_init__(self) -> None:
        n, _ = validate_parameters(
            _exact_integer(self.n, "blocker n"), 1
        )
        barrier_size = _exact_integer(
            self.barrier_size, "barrier size"
        )
        sizes = tuple(
            _exact_integer(size, "odd component size")
            for size in self.odd_component_sizes
        )
        if (
            barrier_size < 0
            or barrier_size >= n // 2
            or len(sizes) != barrier_size + 2
            or tuple(sorted(sizes, reverse=True)) != sizes
            or any(size < 1 or size % 2 == 0 for size in sizes)
            or sum(sizes) != n - barrier_size
        ):
            raise KrennPerfectMatchingBlockerError(
                "invalid odd-partition Tutte blocker type"
            )
        object.__setattr__(self, "n", n)
        object.__setattr__(self, "barrier_size", barrier_size)
        object.__setattr__(self, "odd_component_sizes", sizes)

    @property
    def barrier_vertices(self) -> tuple[int, ...]:
        return tuple(range(self.barrier_size))

    @property
    def components(self) -> tuple[tuple[int, ...], ...]:
        result = []
        start = self.barrier_size
        for size in self.odd_component_sizes:
            result.append(tuple(range(start, start + size)))
            start += size
        return tuple(result)

    @property
    def blocker_edges(self) -> tuple[Edge, ...]:
        component_by_vertex = {
            vertex: component
            for component, vertices in enumerate(self.components)
            for vertex in vertices
        }
        return tuple(
            (first, second)
            for first, second in canonical_edges(self.n)
            if (
                first not in self.barrier_vertices
                and second not in self.barrier_vertices
                and component_by_vertex[first]
                != component_by_vertex[second]
            )
        )

    @property
    def live_edges(self) -> tuple[Edge, ...]:
        blocker = set(self.blocker_edges)
        return tuple(
            edge
            for edge in canonical_edges(self.n)
            if edge not in blocker
        )

    @property
    def labeled_orbit_size(self) -> int:
        denominator = factorial(self.barrier_size)
        for size in self.odd_component_sizes:
            denominator *= factorial(size)
        for multiplicity in Counter(
            self.odd_component_sizes
        ).values():
            denominator *= factorial(multiplicity)
        return factorial(self.n) // denominator

    @property
    def chart_vertex_count(self) -> int:
        return self.n - self.barrier_size

    @property
    def qutrit_chart_variable_count(self) -> int:
        return 2 * self.chart_vertex_count

    @property
    def qutrit_chart_is_square(self) -> bool:
        return (
            len(self.blocker_edges)
            == self.qutrit_chart_variable_count
        )

    def as_record(self) -> dict[str, object]:
        return {
            "n": self.n,
            "barrier_size": self.barrier_size,
            "odd_component_sizes": list(self.odd_component_sizes),
            "blocker_edge_count": len(self.blocker_edges),
            "live_edge_count": len(self.live_edges),
            "labeled_orbit_size": self.labeled_orbit_size,
            "qutrit_chart_variable_count": (
                self.qutrit_chart_variable_count
            ),
            "qutrit_chart_is_square": self.qutrit_chart_is_square,
        }


def perfect_matching_blocker_types(
    n: int,
) -> tuple[PerfectMatchingBlockerType, ...]:
    """Enumerate all minimal-blocker orbit types on ``K_n``."""

    n, _ = validate_parameters(_exact_integer(n, "blocker n"), 1)
    result = []
    for barrier_size in range(n // 2):
        for sizes in _odd_partitions(
            n - barrier_size, barrier_size + 2
        ):
            result.append(
                PerfectMatchingBlockerType(
                    n=n,
                    barrier_size=barrier_size,
                    odd_component_sizes=sizes,
                )
            )
    return tuple(result)


def is_minimal_perfect_matching_blocker(
    n: int,
    edges: Sequence[Sequence[int]],
) -> bool:
    """Check the blocker and inclusion-minimality conditions exactly."""

    n, _ = validate_parameters(_exact_integer(n, "blocker n"), 1)
    blocker_edges = tuple(_canonical_edge(n, edge) for edge in edges)
    if len(blocker_edges) != len(set(blocker_edges)):
        raise KrennPerfectMatchingBlockerError(
            "blocker edges must be unique"
        )
    blocker = set(blocker_edges)
    matchings = perfect_matchings(n)
    if not blocker or any(
        blocker.isdisjoint(matching) for matching in matchings
    ):
        return False
    return all(
        any(
            (blocker - {edge}).isdisjoint(matching)
            for matching in matchings
        )
        for edge in blocker
    )


def blocker_census(n: int) -> dict[str, object]:
    """Return the exact orbit and labelled-blocker census."""

    types = perfect_matching_blocker_types(n)
    return {
        "n": int(n),
        "orbit_type_count": len(types),
        "labeled_blocker_count": sum(
            blocker_type.labeled_orbit_size
            for blocker_type in types
        ),
        "types": [
            blocker_type.as_record() for blocker_type in types
        ],
    }


def _checked_orientation_inputs(
    edges: Sequence[Sequence[int]],
    vertices: Sequence[int],
    capacity: int,
) -> tuple[tuple[Edge, ...], tuple[int, ...], int]:
    checked_vertices = tuple(
        _exact_integer(vertex, "orientation vertex")
        for vertex in vertices
    )
    if (
        len(checked_vertices) != len(set(checked_vertices))
        or not checked_vertices
    ):
        raise KrennPerfectMatchingBlockerError(
            "orientation vertices must be distinct and nonempty"
        )
    vertex_set = set(checked_vertices)
    checked_edges = tuple(
        tuple(
            sorted(
                _exact_integer(vertex, "orientation edge vertex")
                for vertex in edge
            )
        )
        for edge in edges
    )
    if (
        any(
            len(edge) != 2
            or edge[0] == edge[1]
            or edge[0] not in vertex_set
            or edge[1] not in vertex_set
            for edge in checked_edges
        )
        or len(checked_edges) != len(set(checked_edges))
    ):
        raise KrennPerfectMatchingBlockerError(
            "orientation edges must be unique pairs on the chosen vertices"
        )
    capacity = _exact_integer(capacity, "orientation capacity")
    if capacity < 0:
        raise KrennPerfectMatchingBlockerError(
            "orientation capacity must be nonnegative"
        )
    return checked_edges, checked_vertices, capacity


def top_chow_coefficient(
    edges: Sequence[Sequence[int]],
    vertices: Sequence[int],
    *,
    capacity: int = 2,
) -> int:
    """Return ``[prod H_v^capacity] prod_(ij)(H_i+H_j)`` exactly."""

    checked_edges, checked_vertices, capacity = (
        _checked_orientation_inputs(edges, vertices, capacity)
    )
    if len(checked_edges) != capacity * len(checked_vertices):
        return 0
    position = {
        vertex: index for index, vertex in enumerate(checked_vertices)
    }
    zero = (0,) * len(checked_vertices)
    coefficients = {zero: 1}
    for first, second in checked_edges:
        updated: dict[tuple[int, ...], int] = {}
        for exponents, coefficient in coefficients.items():
            for endpoint in (first, second):
                index = position[endpoint]
                if exponents[index] >= capacity:
                    continue
                next_exponents = list(exponents)
                next_exponents[index] += 1
                key = tuple(next_exponents)
                updated[key] = updated.get(key, 0) + coefficient
        coefficients = updated
    return coefficients.get(
        (capacity,) * len(checked_vertices), 0
    )


def brute_force_orientation_count(
    edges: Sequence[Sequence[int]],
    vertices: Sequence[int],
    *,
    capacity: int = 2,
) -> int:
    """Independently count endpoint choices with prescribed indegrees."""

    checked_edges, checked_vertices, capacity = (
        _checked_orientation_inputs(edges, vertices, capacity)
    )
    if len(checked_edges) > 20:
        raise KrennPerfectMatchingBlockerError(
            "brute-force orientation audit is capped at 20 edges"
        )
    if len(checked_edges) != capacity * len(checked_vertices):
        return 0
    position = {
        vertex: index for index, vertex in enumerate(checked_vertices)
    }
    result = 0
    for choices in product((0, 1), repeat=len(checked_edges)):
        counts = [0] * len(checked_vertices)
        for edge, choice in zip(
            checked_edges, choices, strict=True
        ):
            counts[position[edge[choice]]] += 1
        if counts == [capacity] * len(checked_vertices):
            result += 1
    return result


@dataclass(frozen=True)
class TutteBarrierAffineChart:
    """A color-normalized pullback of one minimal blocker prime."""

    n: int
    d: int
    color: int
    barrier_vertices: tuple[int, ...]
    components: tuple[tuple[int, ...], ...]
    blocker_edges: tuple[Edge, ...]
    variable_keys: tuple[tuple[int, int], ...]
    equations: tuple[AffinePolynomial, ...]

    def __post_init__(self) -> None:
        n, d = validate_parameters(
            _exact_integer(self.n, "chart n"),
            _exact_integer(self.d, "chart d"),
        )
        color = _exact_integer(self.color, "chart color")
        barrier_vertices = tuple(
            _exact_integer(vertex, "barrier vertex")
            for vertex in self.barrier_vertices
        )
        components = tuple(
            tuple(
                _exact_integer(vertex, "component vertex")
                for vertex in component
            )
            for component in self.components
        )
        all_vertices = (
            barrier_vertices
            + tuple(
                vertex
                for component in components
                for vertex in component
            )
        )
        if (
            color < 0
            or color >= d
            or tuple(sorted(all_vertices)) != tuple(range(n))
            or len(all_vertices) != len(set(all_vertices))
            or len(components) != len(barrier_vertices) + 2
            or any(
                not component or len(component) % 2 == 0
                for component in components
            )
        ):
            raise KrennPerfectMatchingBlockerError(
                "affine chart does not encode a Tutte barrier"
            )
        object.__setattr__(self, "n", n)
        object.__setattr__(self, "d", d)
        object.__setattr__(self, "color", color)
        object.__setattr__(
            self, "barrier_vertices", barrier_vertices
        )
        object.__setattr__(self, "components", components)
        outside = tuple(
            vertex
            for component in components
            for vertex in component
        )
        component_by_vertex = {
            vertex: component_index
            for component_index, component in enumerate(components)
            for vertex in component
        }
        expected_blocker_edges = tuple(
            edge
            for edge in canonical_edges(n)
            if (
                edge[0] in component_by_vertex
                and edge[1] in component_by_vertex
                and component_by_vertex[edge[0]]
                != component_by_vertex[edge[1]]
            )
        )
        checked_blocker_edges = tuple(
            _canonical_edge(n, edge) for edge in self.blocker_edges
        )
        if checked_blocker_edges != expected_blocker_edges:
            raise KrennPerfectMatchingBlockerError(
                "affine chart blocker edges do not match its components"
            )
        object.__setattr__(
            self, "blocker_edges", checked_blocker_edges
        )
        expected_variables = tuple(
            (vertex, candidate_color)
            for vertex in outside
            for candidate_color in range(d)
            if candidate_color != color
        )
        variable_keys = tuple(
            tuple(
                _exact_integer(value, "affine variable key")
                for value in key
            )
            for key in self.variable_keys
        )
        if variable_keys != expected_variables:
            raise KrennPerfectMatchingBlockerError(
                "affine chart variable order changed"
            )
        object.__setattr__(self, "variable_keys", variable_keys)
        if len(self.equations) != len(self.blocker_edges):
            raise KrennPerfectMatchingBlockerError(
                "affine chart equation census changed"
            )
        normalized_equations = []
        for equation in self.equations:
            normalized_terms = []
            seen_monomials = set()
            for raw_monomial, raw_coefficient in equation:
                monomial = tuple(
                    _exact_integer(
                        variable, "affine monomial variable"
                    )
                    for variable in raw_monomial
                )
                coefficient = _exact_fraction(
                    raw_coefficient, "affine chart coefficient"
                )
                if (
                    not coefficient
                    or len(monomial) > 2
                    or tuple(sorted(monomial)) != monomial
                    or len(monomial) != len(set(monomial))
                    or any(
                        variable < 0
                        or variable >= len(expected_variables)
                        for variable in monomial
                    )
                    or monomial in seen_monomials
                ):
                    raise KrennPerfectMatchingBlockerError(
                        "affine chart polynomial is not canonical"
                    )
                seen_monomials.add(monomial)
                normalized_terms.append((monomial, coefficient))
            if tuple(sorted(normalized_terms)) != tuple(
                normalized_terms
            ):
                raise KrennPerfectMatchingBlockerError(
                    "affine chart polynomial order changed"
                )
            normalized_equations.append(tuple(normalized_terms))
        object.__setattr__(
            self, "equations", tuple(normalized_equations)
        )

    @property
    def variable_count(self) -> int:
        return len(self.variable_keys)

    @property
    def equation_count(self) -> int:
        return len(self.equations)

    @property
    def square(self) -> bool:
        return self.variable_count == self.equation_count

    def evaluate(
        self,
        values: Sequence[int | Fraction],
    ) -> tuple[Fraction, ...]:
        try:
            vector = tuple(
                _exact_fraction(value, "affine chart value")
                for value in values
            )
        except KrennPerfectMatchingBlockerError as error:
            raise KrennPerfectMatchingBlockerError(
                "affine chart values must be exact rationals"
            ) from error
        if len(vector) != self.variable_count:
            raise KrennPerfectMatchingBlockerError(
                "affine chart vector has the wrong length"
            )
        result = []
        for equation in self.equations:
            total = Fraction(0)
            for monomial, coefficient in equation:
                term = coefficient
                for variable in monomial:
                    term *= vector[variable]
                total += term
            result.append(total)
        return tuple(result)

    def product_covectors(
        self,
        values: Sequence[int | Fraction],
    ) -> tuple[tuple[Fraction, ...], ...]:
        vector = tuple(
            _exact_fraction(value, "affine chart value")
            for value in values
        )
        if len(vector) != self.variable_count:
            raise KrennPerfectMatchingBlockerError(
                "affine chart vector has the wrong length"
            )
        value_by_key = dict(
            zip(self.variable_keys, vector, strict=True)
        )
        barrier = set(self.barrier_vertices)
        covectors = []
        for vertex in range(self.n):
            covector = []
            for candidate_color in range(self.d):
                if vertex in barrier:
                    value = Fraction(
                        int(candidate_color == self.color)
                    )
                elif candidate_color == self.color:
                    value = Fraction(1)
                else:
                    value = value_by_key[(vertex, candidate_color)]
                covector.append(value)
            covectors.append(tuple(covector))
        return tuple(covectors)

    def ghz_contraction(
        self,
        values: Sequence[int | Fraction],
    ) -> Fraction:
        covectors = self.product_covectors(values)
        return sum(
            (
                _product(
                    covectors[vertex][color]
                    for vertex in range(self.n)
                )
                for color in range(self.d)
            ),
            Fraction(0),
        )


def _product(values) -> Fraction:
    result = Fraction(1)
    for value in values:
        result *= value
    return result


def build_tutte_barrier_affine_chart(
    witness: SparseWitness,
    blocker_type: PerfectMatchingBlockerType,
    color: int,
    *,
    vertex_order: Sequence[int] | None = None,
) -> TutteBarrierAffineChart:
    """Pull one blocker type back through ``b_ij=x_i^T W_ij x_j``."""

    if witness.n != blocker_type.n:
        raise KrennPerfectMatchingBlockerError(
            "witness and blocker dimensions do not match"
        )
    color = _exact_integer(color, "chart color")
    if color < 0 or color >= witness.d:
        raise KrennPerfectMatchingBlockerError(
            "chart color is outside range(d)"
        )
    order = (
        tuple(range(witness.n))
        if vertex_order is None
        else tuple(
            _exact_integer(vertex, "vertex order")
            for vertex in vertex_order
        )
    )
    if tuple(sorted(order)) != tuple(range(witness.n)):
        raise KrennPerfectMatchingBlockerError(
            "vertex order must be a permutation of range(n)"
        )
    barrier_vertices = tuple(
        order[vertex] for vertex in blocker_type.barrier_vertices
    )
    components = tuple(
        tuple(order[vertex] for vertex in component)
        for component in blocker_type.components
    )
    blocker_edges = tuple(
        sorted(
            (
                min(order[first], order[second]),
                max(order[first], order[second]),
            )
            for first, second in blocker_type.blocker_edges
        )
    )
    outside = tuple(
        vertex for component in components for vertex in component
    )
    variable_keys = tuple(
        (vertex, candidate_color)
        for vertex in outside
        for candidate_color in range(witness.d)
        if candidate_color != color
    )
    variable_by_key = {
        key: index for index, key in enumerate(variable_keys)
    }
    witness_values = witness.as_dict()
    equations = []
    for first, second in blocker_edges:
        terms: dict[AffineMonomial, Fraction] = {}
        for first_color in range(witness.d):
            for second_color in range(witness.d):
                coefficient = witness_values.get(
                    variable_index(
                        witness.n,
                        witness.d,
                        first,
                        second,
                        first_color,
                        second_color,
                    ),
                    Fraction(0),
                )
                if not coefficient:
                    continue
                monomial = []
                if first_color != color:
                    monomial.append(
                        variable_by_key[(first, first_color)]
                    )
                if second_color != color:
                    monomial.append(
                        variable_by_key[(second, second_color)]
                    )
                key = tuple(sorted(monomial))
                terms[key] = terms.get(key, Fraction(0)) + coefficient
        equations.append(
            tuple(
                (monomial, coefficient)
                for monomial, coefficient in sorted(terms.items())
                if coefficient
            )
        )
    return TutteBarrierAffineChart(
        n=witness.n,
        d=witness.d,
        color=color,
        barrier_vertices=barrier_vertices,
        components=components,
        blocker_edges=blocker_edges,
        variable_keys=variable_keys,
        equations=tuple(equations),
    )


